import { SAGAN } from './historia-terreno.js'

// Carl Sagan Station: a playable reconstruction of the 1997 Mars Pathfinder site.
// Geometry is procedural; the two rovers use the original local GLB models.
const LANDER = { x: 0, z: -2.5 }
const HABITAT = { x: 10, z: -8 }

const glow = (T, color) => new T.MeshBasicMaterial({ color })
const metal = (T, color, roughness = .62, metalness = .32) => new T.MeshStandardMaterial({ color, roughness, metalness })

function signo(T, titulo, linea, sub) {
  const c = globalThis.document?.createElement?.('canvas')
  const g = c?.getContext?.('2d')
  if (!g) return null
  c.width = 1024
  c.height = 256
  g.fillStyle = '#16262b'
  g.fillRect(0, 0, 1024, 256)
  g.fillStyle = '#a9f0df'
  g.fillRect(34, 30, 150, 7)
  g.font = 'bold 30px monospace'
  g.fillText(titulo, 36, 84)
  g.font = 'bold 62px sans-serif'
  g.fillText(linea, 34, 150, 940)
  g.fillStyle = '#243a40'
  g.fillRect(36, 172, 952, 3)
  g.fillStyle = '#bde3d8'
  g.font = '27px monospace'
  g.fillText(sub, 36, 214, 940)
  for (const [x, y] of [[20, 20], [997, 20], [20, 231], [997, 231]]) {
    g.fillStyle = '#5a6a66'
    g.beginPath(); g.arc(x, y, 4, 0, Math.PI * 2); g.fill()
  }
  const tex = new T.CanvasTexture(c)
  tex.colorSpace = T.SRGBColorSpace
  return new T.MeshBasicMaterial({ map: tex })
}

// Minimal glTF 2.0 binary reader: the project models are untextured, single-node
// GLBs generated by modelos/generar.py, so no external loader is bundled.
export async function cargarGlb(T, url) {
  const respuesta = await fetch(url)
  if (!respuesta.ok) throw new Error(`${url}: HTTP ${respuesta.status}`)
  const buffer = await respuesta.arrayBuffer()
  const vista = new DataView(buffer)
  if (vista.getUint32(0, true) !== 0x46546c67) throw new Error(`${url}: no es GLB`)
  const total = Math.min(vista.getUint32(8, true), buffer.byteLength)
  let offset = 12, doc, bin
  const texto = new TextDecoder()
  while (offset + 8 <= total) {
    const largo = vista.getUint32(offset, true)
    const tipo = vista.getUint32(offset + 4, true)
    const cuerpo = buffer.slice(offset + 8, offset + 8 + largo)
    if (tipo === 0x4e4f534a) doc = JSON.parse(texto.decode(new Uint8Array(cuerpo)))
    else if (tipo === 0x004e4942) bin = cuerpo
    offset += 8 + largo
  }
  if (!doc?.meshes) throw new Error(`${url}: glTF inválido`)
  const tipos = { SCALAR: 1, VEC2: 2, VEC3: 3 }
  const leer = index => {
    const accessor = doc.accessors[index]
    const view = doc.bufferViews[accessor.bufferView]
    const componente = accessor.componentType === 5126 ? 4 : 2
    const componentes = tipos[accessor.type]
    const inicio = (view.byteOffset ?? 0) + (accessor.byteOffset ?? 0)
    const copia = bin.slice(inicio, inicio + accessor.count * componentes * componente)
    return accessor.componentType === 5126
      ? new Float32Array(copia)
      : new Uint16Array(copia)
  }
  const grupo = new T.Group()
  const cache = new Map()
  const material = index => {
    if (cache.has(index)) return cache.get(index)
    const pbr = doc.materials?.[index]?.pbrMetallicRoughness ?? {}
    const [r, g, b] = pbr.baseColorFactor ?? [1, 1, 1, 1]
    const m = new T.MeshStandardMaterial({
      color: new T.Color().setRGB(r, g, b),
      metalness: pbr.metallicFactor ?? 0,
      roughness: pbr.roughnessFactor ?? 1,
    })
    cache.set(index, m)
    return m
  }
  for (const malla of doc.meshes) {
    for (const primitiva of malla.primitives ?? []) {
      const geometry = new T.BufferGeometry()
      const attrs = primitiva.attributes
      geometry.setAttribute('position', new T.BufferAttribute(leer(attrs.POSITION), 3))
      if (attrs.NORMAL !== undefined) geometry.setAttribute('normal', new T.BufferAttribute(leer(attrs.NORMAL), 3))
      if (primitiva.indices !== undefined) geometry.setIndex(new T.BufferAttribute(leer(primitiva.indices), 1))
      if (attrs.NORMAL === undefined) geometry.computeVertexNormals()
      const mesh = new T.Mesh(geometry, material(primitiva.material ?? 0))
      mesh.frustumCulled = true
      grupo.add(mesh)
    }
  }
  return grupo
}

export function crearEstacionSagan(T, world, height) {
  const grupo = new T.Group()
  grupo.name = 'estación científica Sagan'
  grupo.position.set(SAGAN.x, height(SAGAN.x, SAGAN.z), SAGAN.z)
  world.add(grupo)
  const y = height(SAGAN.x, SAGAN.z)
  const blanco = metal(T, 0xd8d2c2, .54, .18), gris = metal(T, 0x6f767a, .52, .5)
  const negro = metal(T, 0x25282a, .7, .2), ambar = glow(T, 0xffb066)
  const azul = metal(T, 0x334f87, .4, .35), lona = metal(T, 0xc9b17a, .86, .05)
  const box = (w, h, l, x, y0, z, m, parent = grupo) => {
    const o = new T.Mesh(new T.BoxGeometry(w, h, l), m)
    o.position.set(x, y0 + h / 2, z)
    parent.add(o)
    return o
  }
  const cyl = (r, h, x, y0, z, m, parent = grupo, lados = 20) => {
    const o = new T.Mesh(new T.CylinderGeometry(r, r, h, lados), m)
    o.position.set(x, y0 + h / 2, z)
    parent.add(o)
    return o
  }

  // Circular service pad and painted ring.
  const padTex = (() => {
    const c = globalThis.document?.createElement?.('canvas'), g = c?.getContext?.('2d')
    if (!g) return null
    c.width = c.height = 512
    g.clearRect(0, 0, 512, 512)
    g.strokeStyle = 'rgba(232,206,168,.75)'; g.lineWidth = 12
    g.beginPath(); g.arc(256, 256, 232, 0, Math.PI * 2); g.stroke()
    g.lineWidth = 3
    for (let i = 0; i < 36; i++) {
      const a = i / 36 * Math.PI * 2
      g.beginPath(); g.moveTo(256 + Math.cos(a) * 205, 256 + Math.sin(a) * 205)
      g.lineTo(256 + Math.cos(a) * 228, 256 + Math.sin(a) * 228); g.stroke()
    }
    g.fillStyle = 'rgba(232,206,168,.8)'; g.font = 'bold 54px monospace'; g.textAlign = 'center'
    g.fillText('SAGAN', 256, 214); g.font = 'bold 26px monospace'; g.fillText('MARS PATHFINDER', 256, 320)
    const tex = new T.CanvasTexture(c); tex.colorSpace = T.SRGBColorSpace
    return tex
  })()
  if (padTex) {
    const pad = new T.Mesh(new T.CircleGeometry(15, 48), new T.MeshBasicMaterial({ map: padTex, transparent: true, depthWrite: false }))
    pad.rotation.x = -Math.PI / 2
    pad.position.y = .02
    grupo.add(pad)
  }

  // Habitat module: white cylinder, cab windows, entry lock, solar array.
  const hab = new T.Group()
  hab.position.set(HABITAT.x, 0, HABITAT.z)
  grupo.add(hab)
  const cuerpo = new T.Mesh(new T.CylinderGeometry(2.6, 2.6, 6.4, 24), blanco)
  cuerpo.rotation.z = Math.PI / 2
  cuerpo.position.y = 2.7
  hab.add(cuerpo)
  for (const s of [-1, 1]) {
    const tapa = new T.Mesh(new T.SphereGeometry(2.6, 24, 12, 0, Math.PI * 2, 0, Math.PI / 2), blanco)
    tapa.rotation.z = s > 0 ? -Math.PI / 2 : Math.PI / 2
    tapa.position.set(s * 3.2, 2.7, 0)
    hab.add(tapa)
  }
  const ventana = new T.Mesh(new T.CircleGeometry(.85, 24), metal(T, 0x2c4a55, .18, .7))
  ventana.position.set(-.2, 2.9, 2.62)
  hab.add(ventana)
  const marco = new T.Mesh(new T.TorusGeometry(.9, .09, 8, 28), gris)
  marco.position.copy(ventana.position)
  hab.add(marco)
  box(1.8, 2.4, .9, 2.9, 0, -.6, gris, hab)
  box(1.8, 2.4, .1, 2.9, 0, -1.06, negro, hab)
  box(.5, 2.4, .08, 2.9, 0, -1.12, ambar, hab)
  box(4.6, .16, 3.2, -2.4, 0, -.4, gris, hab)
  for (let i = 0; i < 3; i++) {
    const panel = new T.Mesh(new T.BoxGeometry(2.4, .06, 1.5), azul)
    panel.position.set(-4 + i * 2.6, .34, -.4)
    panel.rotation.x = -.32
    hab.add(panel)
  }
  for (const s of [-1, 1]) {
    const pata = new T.Mesh(new T.CylinderGeometry(.12, .16, .34, 10), gris)
    pata.position.set(-4 + (s < 0 ? 0 : 5.2), .16, -.4)
    hab.add(pata)
  }
  // Antenna dish on a mast.
  const mastil = cyl(.14, 4.6, -2.6, 0, 1.7, gris, hab, 12)
  mastil.position.y = 2.3
  const plato = new T.Mesh(new T.SphereGeometry(1.35, 24, 12, 0, Math.PI * 2, 0, .9), metal(T, 0xe2ded1, .5, .3))
  plato.position.set(-2.6, 5.1, 1.7)
  plato.rotation.set(2.2, .4, 0)
  plato.material.side = T.DoubleSide
  hab.add(plato)

  // Beacon: tall amber mast visible through the dust.
  const torre = cyl(.16, 9.5, 6.4, 0, 3.2, gris, grupo, 10)
  torre.position.y = 4.75
  const baliza = new T.Mesh(new T.SphereGeometry(.42, 16, 12), ambar)
  baliza.position.set(6.4, 9.7, 3.2)
  grupo.add(baliza)
  const halo = new T.PointLight(0xffa860, 6, 46, 2)
  halo.position.copy(baliza.position)
  grupo.add(halo)

  // Sagan Station sign, facing the approach from the crash site.
  const letreroMat = signo(T, 'CIENCIA / 1977', 'ESTACIÓN SAGAN', 'MARS PATHFINDER · SOJOURNER · ARES VALLIS')
  const poste = cyl(.1, 2.6, -6.2, 0, 7.4, gris, grupo, 8)
  poste.position.y = 1.3
  if (letreroMat) {
    const letrero = new T.Mesh(new T.PlaneGeometry(3.4, .85), letreroMat)
    letrero.position.set(-6.2, 2.5, 7.4)
    letrero.rotation.y = Math.atan2(-SAGAN.x, -SAGAN.z)
    grupo.add(letrero)
  }
  box(1.2, .9, .9, -4.2, 0, 6.2, lona)
  box(1.2, 1.2, .8, 4.6, 0, 6.6, gris)

  // The historical lander and rover arrive lazily, only when the player is near.
  let cargando = false, cargado = false, disposed = false
  let velocidadBaliza = 0
  async function cargarModelos() {
    if (cargando || cargado || typeof fetch !== 'function') return
    cargando = true
    try {
      const [lander, rover] = await Promise.all([
        cargarGlb(T, './modelos/pathfinder.glb'),
        cargarGlb(T, './modelos/sojourner.glb'),
      ])
      if (disposed) return
      lander.position.set(LANDER.x, y, LANDER.z)
      lander.rotation.y = .62
      grupo.add(lander)
      rover.position.set(LANDER.x + 2.5, y + .02, LANDER.z - 1.5)
      rover.rotation.y = .2
      rover.scale.setScalar(1.6)
      grupo.add(rover)
      const cartel = signo(T, 'OBJETO / 01', 'PATHFINDER', 'ATERRIZÓ EL 4 DE JULIO DE 1997')
      if (cartel) {
        const panel = new T.Mesh(new T.PlaneGeometry(1.9, .48), cartel)
        panel.position.set(LANDER.x - .2, y + .5, LANDER.z + 3.1)
        panel.rotation.y = .1
        grupo.add(panel)
      }
      cargado = true
    } catch (error) {
      console.warn('No se pudieron cargar los modelos de Sagan:', error)
    } finally { cargando = false }
  }

  const choques = [
    { x: LANDER.x, z: LANDER.z, r: 2.1 },
    { x: HABITAT.x, z: HABITAT.z, r: 4.1 },
    { x: 6.4, z: 3.2, r: .7 },
    { x: LANDER.x + 2.5, z: LANDER.z - 1.5, r: 1.3 },
  ]
  function permite(x, z, radio = 0) {
    const dx = x - SAGAN.x, dz = z - SAGAN.z
    return !choques.some(c => Math.hypot(dx - c.x, dz - c.z) < c.r + radio)
  }
  function update(dt, pos) {
    if (!cargado && !cargando && pos && Math.hypot(pos.x - SAGAN.x, pos.z - SAGAN.z) < 260) cargarModelos()
    velocidadBaliza += dt
    const pulso = .55 + .45 * Math.sin(velocidadBaliza * 2.2)
    baliza.scale.setScalar(.85 + pulso * .35)
    halo.intensity = 3 + pulso * 5
  }
  function dispose() {
    disposed = true
    grupo.traverse(o => {
      if (o.geometry) o.geometry.dispose()
      const mats = o.material ? [].concat(o.material) : []
      for (const m of mats) { m.map?.dispose?.(); m.dispose?.() }
    })
  }
  return { permite, update, dispose, grupo, SAGAN }
}
